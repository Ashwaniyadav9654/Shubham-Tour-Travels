/**
 * Optional local add-ons offered in the trip builder, per package.
 * Lists follow what tour operators (MakeMyTrip, Thrillophilia, Holidify,
 * TravelTriangle and others) commonly sell at each destination. Tickets,
 * rides and permits are paid separately unless the team quotes them in,
 * so nothing here carries a price.
 */
export interface Activity {
  id: string
  name: string
  /** Rough time needed, shown as a hint. */
  duration: string
}

const list = (...items: [string, string][]): Activity[] =>
  items.map(([name, duration]) => ({
    id: name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''),
    name,
    duration,
  }))

